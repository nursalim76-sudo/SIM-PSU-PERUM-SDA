function makeDocs(statuses: Array<'Valid' | 'Perlu Revisi' | 'Menunggu Verifikasi' | 'Belum Unggah'>) {
  return ADMIN_DOC_TEMPLATES.map((tpl, idx) => {
    const st = statuses[idx] || 'Belum Unggah';
    return {
      ...tpl,
      status: st,
      fileName: st === 'Belum Unggah' ? undefined : `berkas_${tpl.id}_verified.pdf`,
      uploadedAt: st === 'Belum Unggah' ? undefined : '2026-08-14',
      verifiedBy: st === 'Valid' ? 'Tim Sekretariat DP2CKTR' : undefined,
      revisionNote:
        st === 'Perlu Revisi'
          ? 'Mohon lampirkan salinan pemecahan sertifikat bidang PSU yang telah dilegalisir BPN Sidoarjo.'
          : undefined,
    };
  });
}

function makeChecklist(
  scaleFactor: number,
  actualRatio: number,
  checked = true,
  rthRatioOverride?: number
): PhysicalChecklistItem[] {
  const base: Array<Omit<PhysicalChecklistItem, 'actualVolume' | 'condition'>> = [
    { id: 'phy-1', category: 'Prasarana', name: 'Jaringan Jalan Lingkungan (Aspal/Paving)', unit: 'm²', siteplanVolume: Math.round(6200 * scaleFactor) },
    { id: 'phy-2', category: 'Prasarana', name: 'Jaringan Drainase (U-Ditch Beton)', unit: 'm¹', siteplanVolume: Math.round(1450 * scaleFactor) },
    { id: 'phy-3', category: 'Prasarana', name: 'Sanitasi / IPAL Komunal', unit: 'unit', siteplanVolume: Math.max(1, Math.round(2 * scaleFactor)) },
    { id: 'phy-4', category: 'Prasarana', name: 'Persampahan (TPS / TPS3R)', unit: 'm²', siteplanVolume: Math.round(180 * scaleFactor) },
    { id: 'phy-5', category: 'Prasarana', name: 'Ruang Terbuka Hijau (RTH) & Taman', unit: 'm²', siteplanVolume: Math.round(3200 * scaleFactor) },
    { id: 'phy-6', category: 'Sarana', name: 'Sarana Peribadatan (Musholla/Masjid)', unit: 'm²', siteplanVolume: Math.round(450 * scaleFactor) },
    { id: 'phy-7', category: 'Sarana', name: 'Sarana Rekreasi & Olahraga', unit: 'm²', siteplanVolume: Math.round(600 * scaleFactor) },
    { id: 'phy-8', category: 'Sarana', name: 'Balai Warga / Fasilitas Umum', unit: 'm²', siteplanVolume: Math.round(250 * scaleFactor) },
    { id: 'phy-9', category: 'Utilitas', name: 'Jaringan Air Bersih (PDAM Delta Tirta)', unit: 'm¹', siteplanVolume: Math.round(1600 * scaleFactor) },
    { id: 'phy-10', category: 'Utilitas', name: 'Jaringan Listrik & Penerangan Jalan Umum (PJU)', unit: 'titik', siteplanVolume: Math.round(42 * scaleFactor) },
    { id: 'phy-11', category: 'Utilitas', name: 'Jaringan Telekomunikasi & Fiber Optik', unit: 'm¹', siteplanVolume: Math.round(1350 * scaleFactor) },
    { id: 'phy-12', category: 'Utilitas', name: 'Proteksi Kebakaran (Hidran Kawasan)', unit: 'unit', siteplanVolume: Math.max(2, Math.round(4 * scaleFactor)) },
  ];

  return base.map((item) => {
    if (!checked) {
      return { ...item, actualVolume: 0, condition: 'Belum Diperiksa' };
    }
    const ratio = item.id === 'phy-5' && rthRatioOverride !== undefined ? rthRatioOverride : actualRatio;
    const actualVolume =
      item.unit === 'unit' || item.unit === 'titik'
        ? Math.max(1, Math.round(item.siteplanVolume * ratio))
        : Math.round(item.siteplanVolume * ratio);
    return {
      ...item,
      actualVolume,
      condition: ratio < 0.95 ? 'Perlu Perbaikan' : 'Baik',
    };
  });
}

